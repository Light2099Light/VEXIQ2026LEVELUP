void runCommands(Bot bot)
{
	BaseCommand& command = bot.commands[bot.index];
	switch(command.commandType)
	{
		case AttachMotorRec:
		{
			printf("attach");
			MoveAttachMotorData data;
			
			memcpy(&data, &command, sizeof(MoveAttachMotorData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();


		}
		break;

		case MoveByDegreesRec:
		{
			RobotDrivetrainData data;

			memcpy(&data, &command, sizeof(RobotDrivetrainData));

			configure(&data);



			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();




		}

		break;

		case AttachMotor:
		{
			MoveAttachMotorData data;

			memcpy(&data, &command, sizeof(MoveAttachMotorData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();


		}
		break;

		case SetPneumatic:
		{
			SetPneumaticData data;

			memcpy(&data, &command, sizeof(SetPneumaticData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();


		}
		break;

		case MoveByDegrees:
		{

			printf("drive");

			bool isLeftStalled = initiateStall((MotorData&)bot.left);
			bool isRightStalled = initiateStall((MotorData&)bot.right);
			bool isCenterStalled = initiateStall((MotorData&)bot.center);

			if(isLeftStalled ||
			   isRightStalled ||
			   isCenterStalled)
			{
				bot.isRecovery = true;
			}

			RobotDrivetrainData data;

			memcpy(&data, &command, sizeof(RobotDrivetrainData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();
		}
		break;

		case TurnByGyro:
		{
			TurnByGyroData data;

			memcpy(&data, &command, sizeof(TurnByGyroData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();
		}
		break;

		case WaitUntilPressed:
		{
			WaitUntilLedPressedData data;

			memcpy(&data, &command, sizeof(WaitUntilLedPressedData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();
		}
		break;

		case DriveUntilBeanBag:
		{
			DriveUntilBeanBagData data;

			memcpy(&data, &command, sizeof(DriveUntilBeanBagData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();
		}

		case ParallelRun:
		{
			ParallelData data;

			memcpy(&data, &command, sizeof(ParallelData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

		}

		case DriveInCurve:
		{
			printf("curve");
			
			CurveData data;

			memcpy(&data, &command, sizeof(CurveData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();
		}

		case StopRecovery:
		{
			bot.isRecovery = false;
		}
		break;

		case Stop:
		{
			while(true)
			{
				wait(200, msec);
			}
		}
		break;
	}

}
void RecoveryChecker(bool& isCheckForRecovery, int startindex, int endindex)
{
	if(bot.index >= startindex && bot.index <= endindex)
	{
		isCheckForRecovery = true;
	}
	else
	{
		isCheckForRecovery = false;
	}
}


